"""Exercise broken TEMP, fixed AppData default and explicit test installation.

Directory, registry and shortcut fallback use real permission probes. No
registration-free installer variant is compiled for this verification.
"""
import argparse
import json
import mmap
import os
from pathlib import Path
import subprocess
import sys
import uuid

from build import ROOT, NAME, digest

HIDDEN = 0x08000000


def run(executable, args, env, expected=0, timeout=300):
    try:
        result = subprocess.run([str(executable), *args], env=env, timeout=timeout, creationflags=HIDDEN)
    except OSError as exc:
        if getattr(exc, 'winerror', None) == 740:
            raise RuntimeError('The installer now requests administrator rights. Run CLI verification from an elevated terminal.') from exc
        raise
    if result.returncode != expected:
        raise RuntimeError(f'{executable.name}: exit {result.returncode}, expected {expected}')


def latest_log(executable, before):
    logs = set((executable.parent / 'DrawingStudio-Setup-Temp').glob('DrawingStudio-install-*.log')) - before
    if len(logs) != 1:
        raise AssertionError(f'Expected one bootstrap log, found {len(logs)}')
    path = logs.pop()
    return path, path.read_text(encoding='utf-8')


def bootstrap(executable, env, extra=(), expected=0):
    parent = executable.parent / 'DrawingStudio-Setup-Temp'
    before = set(parent.glob('DrawingStudio-install-*.log'))
    run(executable, ['/VERYSILENT', '/SUPPRESSMSGBOXES', *extra], env, expected)
    log, text = latest_log(executable, before)
    assert 'Temporary payload cleaned.' in text, text
    assert not list(parent.glob('tuxu-*')), 'Temporary extraction directory leaked'
    return log, text


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--installer', type=Path, default=ROOT / '安装包/Windows' / NAME)
    parser.add_argument('--payload', type=Path, default=ROOT / '_rea_temp/windows-installer/release' / NAME,
        help='Raw public Inno payload for corruption test; generated by build.py')
    parser.add_argument('--expected-directory', type=Path,
        help='Explicitly authorize verification of an actual installation directory outside the test workspace')
    parser.add_argument('--keep-installed', action='store_true', help='Leave the verified application installed')
    args = parser.parse_args()
    setup = args.installer.resolve()
    work = ROOT / '_rea_temp/windows-installer' / ('verify-' + uuid.uuid4().hex[:8])
    work.mkdir(parents=True)
    report = {'installerSha256': digest(setup), 'bootstrapChecks': [], 'scope':
        'Actual public package: broken TEMP, fixed AppData default, explicit workspace test directory, real directory/registry/shortcut '
        'permission probes, startup and uninstall. Standard registry and shell integration are '
        'created only where the actual Windows permissions allow them.'}
    blocked_file = work / 'temp-is-a-file'
    blocked_file.write_text('not a directory', encoding='utf-8')
    cases = [('temp-is-file', str(blocked_file)),
        ('temp-is-protected', 'C:/Windows/System32/config'),
        ('temp-invalid-path', str(work / 'invalid"temp'))]
    for label, temp in cases:
        env = dict(os.environ, TEMP=temp, TMP=temp)
        log, text = bootstrap(setup, env, ['/BOOTSTRAPCHECK'])
        assert 'Payload SHA256 verified=' in text
        assert 'Preparation check passed' in text
        selected = next(line.split('=', 1)[1] for line in text.splitlines() if line.startswith('Selected TEMP='))
        assert Path(selected).is_dir(), 'Child TEMP must remain available after payload cleanup'
        assert os.environ.get('TEMP') != temp, 'Parent environment unexpectedly changed'
        report['bootstrapChecks'].append({'case': label, 'passed': True, 'log': str(log)})
        print('PASS bootstrap:', label, flush=True)

    # Corrupt an actual embedded payload byte. The child must never be started.
    corrupt = work / 'corrupt-Setup.exe'
    import shutil
    shutil.copyfile(setup, corrupt)
    with args.payload.open('rb') as stream:
        prefix = stream.read(128)
    with corrupt.open('r+b') as stream, mmap.mmap(stream.fileno(), 0) as data:
        offset = data.find(prefix)
        assert offset >= 0, 'Embedded Inno payload not found'
        data[offset + 256] ^= 1
    env = dict(os.environ, TEMP=str(blocked_file), TMP=str(blocked_file))
    log, text = bootstrap(corrupt, env, ['/BOOTSTRAPCHECK'], expected=1)
    assert '校验失败' in text and 'Installer exit code=' not in text
    report['corruptionRejected'] = True
    print('PASS corrupted payload rejected', flush=True)
    corrupt.unlink()

    log, text = bootstrap(setup, env, ['/DIR=' + str(blocked_file)], expected=1)
    assert '无法写入指定的安装目录' in text and 'Installer exit code=' not in text
    assert 'Payload SHA256 verified=' not in text, 'Invalid explicit target must fail before payload extraction'
    report['unwritableExplicitDirectoryRejectedEarly'] = True
    print('PASS invalid explicit install directory rejected before extraction', flush=True)

    # Verify the default without installing there. A workspace installation uses
    # an explicit /DIR; the launcher must never automatically change the default.
    test_setup = work / '真实安装 空格 中文' / NAME
    test_setup.parent.mkdir()
    shutil.copyfile(setup, test_setup)
    assert digest(test_setup) == digest(setup)
    _, preflight = bootstrap(test_setup, env, ['/BOOTSTRAPCHECK'])
    expected = args.expected_directory.resolve() if args.expected_directory else test_setup.parent / '图序'
    default_directory = Path(os.environ['LOCALAPPDATA']) / 'DrawingStudio'
    assert 'Default install directory=' + str(default_directory) in preflight, 'Default must stay in AppData'
    if args.expected_directory:
        assert expected == default_directory, 'Unexpected installation directory; refusing to install'
        assert args.keep_installed, 'A real user installation must be kept; refusal to uninstall user software'
    else:
        assert 'Uninstall registry allowed=False' in preflight, 'This test expects the restricted build host'
    install_log = work / 'install.inno.log'
    overrides = [] if args.expected_directory else ['/DIR=' + str(expected)]
    _, text = bootstrap(test_setup, env, ['/NORESTART', '/TASKS=desktopicon', '/LOG=' + str(install_log), *overrides])
    assert 'Installer exit code=0' in text
    selected = next(line.split('=', 1)[1] for line in text.splitlines() if line.startswith('Default install directory='))
    installed = Path(selected)
    assert installed == expected
    inno = install_log.read_text(encoding='utf-8-sig', errors='replace')
    assert 'Install directory write check passed:' in inno
    assert 'Exception message:' not in inno and 'Fatal exception' not in inno
    for name in ['打开图序.lnk', '卸载图序.lnk', 'unins000.exe']:
        assert (installed / name).is_file(), name
    report['installation'] = {'directory': str(installed), 'defaultDirectoryFallback': False, 'noDirOverride': bool(args.expected_directory),
        'samePublicPackage': True, 'noInstallExceptions': True, 'localShortcuts': True,
        'uninstallRegistryAllowed': 'Uninstall registry allowed=True' in text,
        'startMenuAllowed': 'Start menu allowed=True' in text,
        'desktopAllowed': 'Desktop shortcut allowed=True' in text}
    report['files'] = {}
    for name in ['DrawingStudio.exe', 'DrawingStudio.dll', 'ui/index.html', 'content/library.json', 'content/index/catalog.json']:
        assert digest(installed / name) == digest(ROOT / '新版软件/图序-React版' / name), name
        report['files'][name] = True
    print('PASS public installation:', installed, '; no exceptions, local shortcuts, five file hashes match', flush=True)

    # Startup verifier launches from another working directory, with no test flags.
    good_temp = test_setup.parent / 'DrawingStudio-Setup-Temp'
    runtime_env = dict(os.environ, TEMP=str(good_temp), TMP=str(good_temp), STUDIO_OUTPUT=str(installed))
    subprocess.run(['C:/Program Files/nodejs/node.exe', str(ROOT / 'apps/desktop/verify-startup.mjs')],
        env=runtime_env, check=True, timeout=120)
    report['startup'] = json.loads((installed / 'normal-startup-verification.json').read_text(encoding='utf-8-sig'))
    assert report['startup']['passed']
    if args.keep_installed:
        report.update(passed=True, keptInstalled=True, uninstalled=False)
    else:
        sentinel = installed / 'user-data/retain-on-uninstall.txt'
        sentinel.parent.mkdir(exist_ok=True)
        sentinel.write_text('retain settings', encoding='utf-8')
        run(installed / 'unins000.exe', ['/VERYSILENT', '/SUPPRESSMSGBOXES', '/NORESTART'], runtime_env)
        assert not (installed / 'DrawingStudio.exe').exists()
        assert sentinel.read_text(encoding='utf-8') == 'retain settings'
        report.update(passed=True, uninstalled=True, userDataPreserved=True)
    output = work / 'installer-path-fix-verification.json'
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
    (ROOT / '_rea_temp/windows-installer/latest-verification.json').write_text(
        json.dumps({'report': str(output)}, ensure_ascii=False, indent=2), encoding='utf-8')
    print('PASS startup;', 'kept installed' if args.keep_installed else 'uninstall and retained user data passed', '; report:', output, flush=True)


if __name__ == '__main__':
    main()
